import SwiftUI
import UIKit

// MARK: - Trade AI Coach Chart Preview Card
// Displays interactive timeframe selector, live candlestick chart (like Replay), or uploaded screenshot
public struct TradeAICoachChartCard: View {
    public let trade: Trade
    public let executions: [Execution]
    public let bars: [MarketBar]?
    @Binding public var selectedResolution: String
    public let selectedChartImage: UIImage?
    public let isAutoGeneratedChart: Bool
    public let activeCandleProvider: String?
    public let activeBarsCount: Int
    public let onResolutionChanged: (String) -> Void
    public let onEnlarge: () -> Void
    public let onUpload: () -> Void
    
    private let resolutions: [(String, String)] = [
        ("5m", "M5"),
        ("15m", "M15"),
        ("1h", "H1"),
        ("4h", "H4")
    ]
    
    public init(
        trade: Trade,
        executions: [Execution],
        bars: [MarketBar]?,
        selectedResolution: Binding<String>,
        selectedChartImage: UIImage?,
        isAutoGeneratedChart: Bool,
        activeCandleProvider: String?,
        activeBarsCount: Int,
        onResolutionChanged: @escaping (String) -> Void,
        onEnlarge: @escaping () -> Void,
        onUpload: @escaping () -> Void
    ) {
        self.trade = trade
        self.executions = executions
        self.bars = bars
        self._selectedResolution = selectedResolution
        self.selectedChartImage = selectedChartImage
        self.isAutoGeneratedChart = isAutoGeneratedChart
        self.activeCandleProvider = activeCandleProvider
        self.activeBarsCount = activeBarsCount
        self.onResolutionChanged = onResolutionChanged
        self.onEnlarge = onEnlarge
        self.onUpload = onUpload
    }
    
    public var body: some View {
        AppCard {
            VStack(alignment: .leading, spacing: 10) {
                // Header: Title + Timeframe Selector
                HStack(alignment: .center) {
                    HStack(spacing: 5) {
                        Image(systemName: "chart.xyaxis.line")
                            .font(AppTypography.cardHeaderUppercase)
                            .foregroundColor(AppColors.brand)
                        Text("CHART STRUCTURE")
                            .font(AppTypography.cardHeaderUppercase)
                            .foregroundColor(AppColors.primaryText)
                    }
                    
                    Spacer()
                    
                    // Timeframe Picker Tabs (M5, M15, H1, H4) matching Market Structure Bias standard
                    AppSegmentedBar(
                        selection: Binding(
                            get: { selectedResolution },
                            set: { newRes in
                                guard selectedResolution != newRes else { return }
                                selectedResolution = newRes
                                onResolutionChanged(newRes)
                            }
                        ),
                        items: resolutions.map { $0.0 },
                        titleFor: { id in
                            resolutions.first(where: { $0.0 == id })?.1 ?? id.uppercased()
                        },
                        height: 28
                    )
                }
                
                // Chart Preview: Custom image if attached, or live interactive CandleChartView
                if let image = selectedChartImage, !isAutoGeneratedChart {
                    ZStack(alignment: .bottomTrailing) {
                        Image(uiImage: image)
                            .resizable()
                            .aspectRatio(contentMode: .fit)
                            .frame(maxWidth: .infinity)
                            .appCardStyle(cornerRadius: 10, padding: 0)
                        
                        ModalCircleButton(icon: "arrow.up.left.and.arrow.down.right", action: onEnlarge)
                            .padding(6)
                    }
                    .contentShape(Rectangle())
                    .onTapGesture {
                        NativeHaptics.lightImpact()
                        onEnlarge()
                    }
                } else if let validBars = bars, !validBars.isEmpty {
                    CandleChartView(
                        visibleBars: validBars,
                        allBars: validBars,
                        totalBarsCount: validBars.count,
                        trade: trade,
                        executions: executions,
                        throughTimestamp: validBars.last?.timestamp ?? Int64(Date().timeIntervalSince1970 * 1000),
                        unrealizedPnl: trade.netPnl,
                        showLiquidity: false,
                        showRSI: true
                    )
                    .frame(height: 250)
                    .appCardStyle(cornerRadius: 10, padding: 0)
                } else {
                    HStack(spacing: 10) {
                        TradeJournalProLoader(size: 28)
                        Text("Fetching \(selectedResolution.uppercased()) candlestick flow & market structure...")
                            .font(AppTypography.caption)
                            .foregroundColor(AppColors.secondaryText)
                        Spacer()
                    }
                    .padding(.vertical, 10)
                }
                
                // Bottom Info & Manual Screenshot Upload
                HStack {
                    if let provider = activeCandleProvider, activeBarsCount > 0 {
                        let cleanProvider = provider
                            .replacingOccurrences(of: "\\s*\\(.*?Cache.*?\\)", with: "", options: .regularExpression)
                            .replacingOccurrences(of: "\\s*\\(Cached\\)", with: "", options: .regularExpression)
                            .trimmingCharacters(in: .whitespaces)
                        Text("\(activeBarsCount) bars • \(cleanProvider)")
                            .font(AppTypography.captionMicro)
                            .foregroundColor(AppColors.brand)
                    } else {
                        Text(isAutoGeneratedChart ? "Live Market Structure" : "Custom Screenshot Attached")
                            .font(AppTypography.captionMicro)
                            .foregroundColor(AppColors.secondaryText)
                    }
                    
                    Spacer()
                    
                    AppSecondaryButton(
                        "Upload Screenshot",
                        icon: "photo.badge.plus",
                        height: 28,
                        action: onUpload
                    )
                }
            }
            .padding(.vertical, 2)
        }
    }
}

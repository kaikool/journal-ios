import SwiftUI
import UIKit

// MARK: - Trade AI Coach Multi-Timeframe Chart Vision Card
// Replicates PreTradeChartCard structure 1:1 with institutional MarketCandleChartView,
// timeframe switching, footprint volume profiles, and landscape expansion.
public struct TradeAICoachChartCard: View {
    public let trade: Trade
    public let executions: [Execution]
    public let bars: [MarketBar]?
    @Binding public var selectedResolution: String
    public let selectedChartImage: UIImage?
    public let isAutoGeneratedChart: Bool
    public let activeCandleProvider: String?
    public let activeBarsCount: Int
    public let onResolutionChanged: (String) -> Void
    public let onEnlarge: () -> Void
    public let onUpload: () -> Void
    public let onInteractionChanged: ((Bool) -> Void)?

    @State private var keyLevels: [KeyLevel] = []
    @State private var sessionProfiles: [SessionProfileSnapshot] = []
    @State private var developingProfile: DevelopingProfile? = nil
    @State private var developingProfiles: [DevelopingProfile] = []
    @State private var patterns: [DetectedCandlePattern] = []

    public init(
        trade: Trade,
        executions: [Execution],
        bars: [MarketBar]?,
        selectedResolution: Binding<String>,
        selectedChartImage: UIImage?,
        isAutoGeneratedChart: Bool,
        activeCandleProvider: String?,
        activeBarsCount: Int,
        onResolutionChanged: @escaping (String) -> Void,
        onEnlarge: @escaping () -> Void,
        onUpload: @escaping () -> Void,
        onInteractionChanged: ((Bool) -> Void)? = nil
    ) {
        self.trade = trade
        self.executions = executions
        self.bars = bars
        self._selectedResolution = selectedResolution
        self.selectedChartImage = selectedChartImage
        self.isAutoGeneratedChart = isAutoGeneratedChart
        self.activeCandleProvider = activeCandleProvider
        self.activeBarsCount = activeBarsCount
        self.onResolutionChanged = onResolutionChanged
        self.onEnlarge = onEnlarge
        self.onUpload = onUpload
        self.onInteractionChanged = onInteractionChanged
    }

    private var activeTimeframeTitle: String {
        MarketResolution.label(for: selectedResolution)
    }

    public var body: some View {
        AppCard {
            VStack(alignment: .leading, spacing: 8) {
                // Header with Timeframe Tabs
                HStack {
                    Text("CHART STRUCTURE")
                        .font(AppTypography.cardHeaderUppercase)
                        .foregroundColor(AppColors.secondaryText)
                        .tracking(0.5)

                    Spacer()

                    // Timeframe Picker Tabs (M5, M15, H1, H4)
                    AppSegmentedBar(
                        selection: Binding(
                            get: { selectedResolution },
                            set: { newRes in
                                guard selectedResolution != newRes else { return }
                                selectedResolution = newRes
                                onResolutionChanged(newRes)
                            }
                        ),
                        items: ["5m", "15m", "1h", "4h"],
                        titleFor: { MarketResolution.label(for: $0) },
                        height: 28
                    )
                }

                // Chart View Container
                if let image = selectedChartImage, !isAutoGeneratedChart {
                    VStack(spacing: 4) {
                        Image(uiImage: image)
                            .resizable()
                            .aspectRatio(contentMode: .fit)
                            .frame(maxWidth: .infinity)
                            .clipShape(RoundedRectangle(cornerRadius: 8))
                            .contentShape(Rectangle())
                            .onTapGesture {
                                NativeHaptics.lightImpact()
                                onEnlarge()
                            }

                        chartFooterActions
                    }
                } else if let validBars = bars, !validBars.isEmpty {
                    VStack(spacing: 4) {
                        MarketCandleChartView(
                            bars: validBars,
                            symbol: trade.symbol,
                            timeframe: activeTimeframeTitle,
                            keyLevels: keyLevels,
                            sessionProfiles: sessionProfiles,
                            developingProfile: developingProfile,
                            developingProfiles: developingProfiles,
                            patterns: patterns,
                            onInteractionChanged: onInteractionChanged
                        )
                        .frame(height: 260)

                        chartFooterActions
                    }
                    .task(id: validBars.count) {
                        let res = await SessionFootprintCoordinator.shared.loadKeyLevels(for: trade.symbol, recentBars: validBars)
                        self.keyLevels = res.levels
                        self.sessionProfiles = res.profiles
                        self.developingProfile = res.developing
                        self.developingProfiles = res.developingProfiles
                        self.patterns = SessionFootprintCoordinator.shared.scanConfluentPatterns(bars: validBars, keyLevels: res.levels)
                    }
                } else {
                    emptyLoadingView
                }
            }
            .padding(.vertical, 2)
        }
    }

    private var chartFooterActions: some View {
        HStack(alignment: .center) {
            HStack(spacing: 5) {
                Circle()
                    .fill(AppColors.profit)
                    .frame(width: 5, height: 5)
                Text("\(activeBarsCount > 0 ? activeBarsCount : (bars?.count ?? 0)) bars")
                    .font(AppTypography.captionMicro)
                    .foregroundColor(AppColors.secondaryText)
            }

            Spacer()

            HStack(spacing: 8) {
                // Attach custom chart image icon button
                ModalCircleButton(icon: "photo.badge.plus", label: "Attach chart image", action: onUpload)

                // Enlarge full-screen lightbox / landscape icon button
                ModalCircleButton(icon: "arrow.up.left.and.arrow.down.right", color: AppColors.brand, label: "Enlarge chart", action: onEnlarge)
            }
        }
        .padding(.horizontal, 2)
        .padding(.top, 2)
    }

    private var emptyLoadingView: some View {
        LoadingView("Fetching \(trade.symbol) \(activeTimeframeTitle) candles...", size: 36)
            .padding(.vertical, 24)
    }
}

import SwiftUI
import UIKit

// MARK: - Trade AI Coach Chart Preview Card
// Displays interactive timeframe selector, candlestick snapshot preview, and lightbox zoom trigger
public struct TradeAICoachChartCard: View {
    @Binding public var selectedResolution: String
    public let selectedChartImage: UIImage?
    public let isAutoGeneratedChart: Bool
    public let activeCandleProvider: String?
    public let activeBarsCount: Int
    public let onResolutionChanged: (String) -> Void
    public let onEnlarge: () -> Void
    public let onUpload: () -> Void
    
    private let resolutions: [(String, String)] = [
        ("5m", "M5"),
        ("15m", "M15"),
        ("1h", "H1"),
        ("4h", "H4")
    ]
    
    public init(
        selectedResolution: Binding<String>,
        selectedChartImage: UIImage?,
        isAutoGeneratedChart: Bool,
        activeCandleProvider: String?,
        activeBarsCount: Int,
        onResolutionChanged: @escaping (String) -> Void,
        onEnlarge: @escaping () -> Void,
        onUpload: @escaping () -> Void
    ) {
        self._selectedResolution = selectedResolution
        self.selectedChartImage = selectedChartImage
        self.isAutoGeneratedChart = isAutoGeneratedChart
        self.activeCandleProvider = activeCandleProvider
        self.activeBarsCount = activeBarsCount
        self.onResolutionChanged = onResolutionChanged
        self.onEnlarge = onEnlarge
        self.onUpload = onUpload
    }
    
    public var body: some View {
        AppCard {
            VStack(alignment: .leading, spacing: 10) {
                // Header: Title + Timeframe Selector
                HStack(alignment: .center) {
                    HStack(spacing: 5) {
                        Image(systemName: "chart.xyaxis.line")
                            .font(.system(size: 11, weight: .bold))
                            .foregroundColor(AppColors.brand)
                        Text("CHART VISION")
                            .font(.system(size: 11, weight: .bold))
                            .foregroundColor(AppColors.primaryText)
                    }
                    
                    Spacer()
                    
                    // Timeframe Picker: M5 | M15 | H1 | H4
                    HStack(spacing: 4) {
                        ForEach(resolutions, id: \.0) { tf in
                            let isSelected = selectedResolution == tf.0
                            Button(action: {
                                guard selectedResolution != tf.0 else { return }
                                selectedResolution = tf.0
                                onResolutionChanged(tf.0)
                            }) {
                                Text(tf.1)
                                    .font(.system(size: 10, weight: isSelected ? .bold : .medium))
                                    .foregroundColor(isSelected ? .white : AppColors.secondaryText)
                                    .padding(.horizontal, 7)
                                    .padding(.vertical, 3)
                                    .background(isSelected ? AppColors.brand : AppColors.secondaryBackground)
                                    .clipShape(Capsule())
                            }
                            .buttonStyle(.plain)
                        }
                    }
                }
                
                // Chart Snapshot Preview (Tap to enlarge in Lightbox)
                if let image = selectedChartImage {
                    Button(action: onEnlarge) {
                        ZStack(alignment: .bottomTrailing) {
                            Image(uiImage: image)
                                .resizable()
                                .scaledToFill()
                                .frame(maxWidth: .infinity)
                                .frame(height: 180)
                                .clipped()
                                .cornerRadius(8)
                                .overlay(RoundedRectangle(cornerRadius: 8).stroke(AppColors.border, lineWidth: 0.8))
                            
                            HStack(spacing: 4) {
                                Image(systemName: "arrow.up.left.and.arrow.down.right")
                                    .font(.system(size: 9, weight: .bold))
                                Text("Expand")
                                    .font(.system(size: 10, weight: .semibold))
                            }
                            .foregroundColor(.white)
                            .padding(.horizontal, 6)
                            .padding(.vertical, 3)
                            .background(Color.black.opacity(0.65))
                            .clipShape(Capsule())
                            .padding(6)
                        }
                    }
                    .buttonStyle(.plain)
                } else {
                    HStack(spacing: 10) {
                        ProgressView()
                            .scaleEffect(0.8)
                        Text("Fetching \(selectedResolution.uppercased()) candlestick flow & chart snapshot...")
                            .font(AppTypography.caption)
                            .foregroundColor(AppColors.secondaryText)
                        Spacer()
                    }
                    .padding(.vertical, 10)
                }
                
                // Bottom Info & Manual Screenshot Upload
                HStack {
                    if let provider = activeCandleProvider, activeBarsCount > 0 {
                        let cleanProvider = provider
                            .replacingOccurrences(of: "\\s*\\(.*?Cache.*?\\)", with: "", options: .regularExpression)
                            .replacingOccurrences(of: "\\s*\\(Cached\\)", with: "", options: .regularExpression)
                            .trimmingCharacters(in: .whitespaces)
                        Text("\(activeBarsCount) bars • \(cleanProvider)")
                            .font(.system(size: 10, weight: .medium))
                            .foregroundColor(AppColors.brand)
                    } else {
                        Text(isAutoGeneratedChart ? "Auto-synced from Market Data" : "Custom Screenshot Attached")
                            .font(.system(size: 10, weight: .medium))
                            .foregroundColor(AppColors.secondaryText)
                    }
                    
                    Spacer()
                    
                    Button(action: onUpload) {
                        HStack(spacing: 4) {
                            Image(systemName: "photo.badge.plus")
                                .font(.system(size: 11))
                            Text("Upload Screenshot")
                                .font(.system(size: 11, weight: .medium))
                        }
                        .foregroundColor(AppColors.secondaryText)
                        .padding(.horizontal, 8)
                        .padding(.vertical, 3)
                        .background(AppColors.secondaryBackground)
                        .clipShape(Capsule())
                    }
                    .buttonStyle(.plain)
                }
            }
            .padding(.vertical, 2)
        }
    }
}

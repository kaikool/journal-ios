import SwiftUI
import UIKit

// MARK: - Risk AI Independent Trading Coach Sheet (Apple HIG Standard)
// Orchestrates multi-timeframe chart replay, profile alignment, critical trade audit, and multi-turn chat
// Architecture: MVVM via TradeAICoachViewModel
public struct TradeAICoachSheet: View {
    @Environment(\.dismiss) private var dismiss
    @EnvironmentObject private var env: AppEnvironment
    @ObservedObject internal var dataStore = TradeDataStore.shared
    @StateObject private var viewModel: TradeAICoachViewModel
    
    public let trade: Trade
    public var onTradeUpdated: ((Trade) -> Void)?
    
    @State private var activeFullScreenModal: AICoachFullScreenModal? = nil

    private enum AICoachFullScreenModal: Identifiable {
        case lightbox(UIImage)
        case landscapeChart

        var id: String {
            switch self {
            case .lightbox: return "lightbox"
            case .landscapeChart: return "landscapeChart"
            }
        }
    }
    
    public init(trade: Trade, onTradeUpdated: ((Trade) -> Void)? = nil) {
        self.trade = trade
        self.onTradeUpdated = onTradeUpdated
        _viewModel = StateObject(wrappedValue: TradeAICoachViewModel(trade: trade, onTradeUpdated: onTradeUpdated))
    }
    
    private var fills: [Execution] {
        dataStore.executions
            .filter { trade.executionIds.contains($0.id) }
            .sorted { $0.executedAt < $1.executedAt }
    }
    
    public var body: some View {
        NavigationStack {
            ScrollView {
                VStack(spacing: 12) {
                    // 1. Trade Context Pill
                    TradeAICoachContextCard(trade: trade, isOpen: viewModel.isOpen)
                    
                    // 1b. Linked Pre-Trade Setup Card (Parsed Execution Blueprint)
                    if let plan = viewModel.linkedPreTradePlan {
                        LinkedPreTradeSetupCard(plan: plan, trade: trade)
                    }
                    
                    // 2. Trader Profile Compliance Pill
                    TradeAICoachCompliancePill(
                        profile: dataStore.aiSettings.traderProfile,
                        onTap: { viewModel.showTraderProfileSheet = true }
                    )
                    
                    // 3. Replay Chart Data Status Card
                    TradeAICoachChartCard(
                        trade: trade,
                        executions: fills,
                        bars: viewModel.activeBars,
                        selectedResolution: $viewModel.selectedResolution,
                        selectedChartImage: viewModel.selectedChartImage,
                        isAutoGeneratedChart: viewModel.isAutoGeneratedChart,
                        activeCandleProvider: viewModel.activeCandleProvider,
                        activeBarsCount: viewModel.activeBarsCount,
                        onResolutionChanged: { _ in
                            Task { await viewModel.runCoachingAnalysis(dataStore: dataStore) }
                        },
                        onEnlarge: {
                            if let img = viewModel.selectedChartImage {
                                activeFullScreenModal = .lightbox(img)
                            } else {
                                activeFullScreenModal = .landscapeChart
                            }
                        },
                        onUpload: { viewModel.showPhotoPicker = true },
                        onInteractionChanged: { isInteracting in
                            viewModel.isChartInteracting = isInteracting
                        }
                    )
                    
                    // 4. Loading, Error, or AI Result Document
                    if viewModel.isLoading {
                        TradeAICoachLoadingCard(isOpen: viewModel.isOpen)
                    } else if let error = viewModel.errorMessage {
                        TradeAICoachErrorCard(message: error, onRetry: {
                            Task { await viewModel.runCoachingAnalysis(dataStore: dataStore) }
                        })
                    } else if !viewModel.coachingResult.isEmpty {
                        // 5. Compact Action Bar (Append to Notes, Save to Notebook, Copy, Regenerate)
                        TradeAICoachActionBar(
                            isSavedToNotes: viewModel.isSavedToNotes,
                            isSavedToNotebook: viewModel.isSavedToNotebook,
                            showCopiedAlert: viewModel.showCopiedAlert,
                            onAppendNotes: { viewModel.appendToNotes(dataStore: dataStore) },
                            onSaveNotebook: { viewModel.saveToNotebook(dataStore: dataStore) },
                            onCopy: { viewModel.copyToClipboard() },
                            onRegenerate: {
                                AICoachSessionStore.shared.clear(key: trade.key)
                                viewModel.followUpMessages = []
                                Task { await viewModel.runCoachingAnalysis(dataStore: dataStore) }
                            }
                        )
                        
                        // 6. Structured Section Cards Reader
                        AIDocumentReaderView(text: viewModel.coachingResult)
                        
                        // 7. Follow-up conversation turns (message bubbles in scroll view)
                        TradeAICoachFollowUpView(
                            coachingResult: viewModel.coachingResult,
                            followUpMessages: viewModel.followUpMessages
                        )
                    }
                }
                .padding(.horizontal, 16)
                .padding(.vertical, 12)
                .padding(.bottom, 24)
            }
            .scrollDisabled(viewModel.isChartInteracting)
            .safeAreaInset(edge: .bottom) {
                if !viewModel.coachingResult.isEmpty && !viewModel.isLoading {
                    TradeAICoachBottomFloatingInput(
                        followUpQuery: $viewModel.followUpQuery,
                        isSubmitting: viewModel.isSubmittingFollowUp,
                        hasHistory: !viewModel.followUpMessages.isEmpty,
                        onResetThread: {
                            viewModel.followUpMessages = []
                            viewModel.followUpQuery = ""
                            AICoachSessionStore.shared.save(key: trade.key, result: viewModel.coachingResult, followUps: [])
                        },
                        onSubmit: {
                            viewModel.submitFollowUpQuestion(dataStore: dataStore)
                        }
                    )
                }
            }
            .background(AppColors.background)
            .navigationTitle(viewModel.isOpen ? "Live Position Coach" : "Post-Trade AI Audit")
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .topBarLeading) {
                    ModalDismissButton { dismiss() }
                }
                
                ToolbarItem(placement: .topBarTrailing) {
                    ModalPrimaryButton("Done") { dismiss() }
                }
            }
            .sheet(isPresented: $viewModel.showPhotoPicker) {
                UIKitImagePicker(isPresented: $viewModel.showPhotoPicker) { data, _ in
                    if let img = UIImage(data: data) {
                        viewModel.selectedChartImage = img
                        viewModel.isAutoGeneratedChart = false
                        Task { await viewModel.runCoachingAnalysis(dataStore: dataStore) }
                    }
                }
            }
            .sheet(isPresented: $viewModel.showTraderProfileSheet) {
                TraderProfileSheet()
            }
            .fullScreenCover(item: $activeFullScreenModal) { modal in
                switch modal {
                case .lightbox(let img):
                    FullScreenChartLightboxView(image: img)
                case .landscapeChart:
                    MarketCandleLandscapeSheet(
                        bars: viewModel.activeBars ?? [],
                        symbol: trade.symbol,
                        selectedTimeframe: $viewModel.selectedResolution,
                        timeframeOptions: ["5m", "15m", "1h", "4h"],
                        timeframeTitle: { MarketResolution.label(for: $0) },
                        onDismiss: { activeFullScreenModal = nil }
                    )
                }
            }
        }
        .task {
            await viewModel.onAppearLoad(dataStore: dataStore)
        }
    }
}

import SwiftUI
import UIKit

// MARK: - Risk AI Independent Trading Coach Sheet (Apple HIG Standard)
// Orchestrates multi-timeframe chart replay, profile alignment, critical trade audit, and multi-turn chat
public struct TradeAICoachSheet: View {
    @Environment(\.dismiss) private var dismiss
    @EnvironmentObject private var env: AppEnvironment
    @ObservedObject private var dataStore = TradeDataStore.shared
    
    public let trade: Trade
    public var onTradeUpdated: ((Trade) -> Void)?
    
    @State private var coachingResult: String = ""
    @State private var isLoading: Bool = false
    @State private var errorMessage: String? = nil
    @State private var isSavedToNotes: Bool = false
    @State private var isSavedToNotebook: Bool = false
    @State private var createdNotebookNoteId: String? = nil
    @State private var showCopiedAlert: Bool = false
    @State private var showTraderProfileSheet: Bool = false
    
    // Candlestick & Multimodal Chart Vision State
    @State private var selectedChartImage: UIImage? = nil
    @State private var isAutoGeneratedChart: Bool = true
    @State private var showPhotoPicker: Bool = false
    @State private var showFullScreenChart: Bool = false
    @State private var hasAutoLoadedAttachment: Bool = false
    @State private var selectedResolution: String = "15m" // "5m", "15m", "1h", "4h"
    @State private var activeCandleProvider: String? = nil
    @State private var activeBarsCount: Int = 0
    @State private var activeBars: [MarketBar]? = nil
    @State private var followUpMessages: [AICoachMessage] = []
    @State private var followUpQuery: String = ""
    @State private var isSubmittingFollowUp: Bool = false
    
    public init(trade: Trade, onTradeUpdated: ((Trade) -> Void)? = nil) {
        self.trade = trade
        self.onTradeUpdated = onTradeUpdated
    }
    
    private var isOpen: Bool {
        trade.status == .open || trade.closedAt == nil
    }
    
    private var linkedPreTradePlan: AdvisorCommitmentRecord? {
        AIAdvisorMemoryEngine.shared.getCommitmentForTrade(trade) ?? AIAdvisorMemoryEngine.shared.getLatestCommitment(for: trade.symbol, beforeOrNear: trade.openedAt)
    }
    
    public var body: some View {
        NavigationStack {
            ScrollView {
                VStack(spacing: 12) {
                    // 1. Trade Context Pill
                    TradeAICoachContextCard(trade: trade, isOpen: isOpen)
                    
                    // 1b. Linked Pre-Trade Plan Banner (Accountability & Continuity)
                    if let plan = linkedPreTradePlan {
                        HStack(spacing: 8) {
                            Image(systemName: "link.badge.plus")
                                .font(.system(size: 13, weight: .bold))
                                .foregroundColor(AppColors.brand)
                            
                            VStack(alignment: .leading, spacing: 2) {
                                HStack(spacing: 6) {
                                    Text("Linked Pre-Trade Setup:")
                                        .font(.system(size: 11, weight: .bold))
                                        .foregroundColor(AppColors.primaryText)
                                    Text("\(plan.bias) \(plan.plannedEntry ?? "")")
                                        .font(.system(size: 11, weight: .bold))
                                        .foregroundColor(AppColors.brand)
                                }
                                Text("AI Coach is held accountable to this plan and will audit execution against it.")
                                    .font(.system(size: 10))
                                    .foregroundColor(AppColors.secondaryText)
                            }
                            
                            Spacer()
                        }
                        .padding(.horizontal, 12)
                        .padding(.vertical, 8)
                        .background(AppColors.brand.opacity(0.1))
                        .clipShape(RoundedRectangle(cornerRadius: 10, style: .continuous))
                        .overlay(
                            RoundedRectangle(cornerRadius: 10, style: .continuous)
                                .stroke(AppColors.brand.opacity(0.35), lineWidth: 0.8)
                        )
                    }
                    
                    // 2. Trader Profile Compliance Pill
                    TradeAICoachCompliancePill(
                        profile: dataStore.aiSettings.traderProfile,
                        onTap: { showTraderProfileSheet = true }
                    )
                    
                    // 3. Replay Chart Data Status Card
                    TradeAICoachChartCard(
                        selectedResolution: $selectedResolution,
                        selectedChartImage: selectedChartImage,
                        isAutoGeneratedChart: isAutoGeneratedChart,
                        activeCandleProvider: activeCandleProvider,
                        activeBarsCount: activeBarsCount,
                        onResolutionChanged: { _ in
                            isAutoGeneratedChart = true
                            selectedChartImage = nil
                            Task { await runCoachingAnalysis() }
                        },
                        onEnlarge: { showFullScreenChart = true },
                        onUpload: { showPhotoPicker = true }
                    )
                    
                    // 4. Loading, Error, or AI Result Document
                    if isLoading {
                        TradeAICoachLoadingCard(isOpen: isOpen)
                    } else if let error = errorMessage {
                        TradeAICoachErrorCard(message: error, onRetry: {
                            Task { await runCoachingAnalysis() }
                        })
                    } else if !coachingResult.isEmpty {
                        // 5. Structured Section Cards Reader
                        AIDocumentReaderView(text: coachingResult)
                        
                        // Follow-up conversation turns & input card
                        TradeAICoachFollowUpView(
                            coachingResult: coachingResult,
                            followUpMessages: $followUpMessages,
                            followUpQuery: $followUpQuery,
                            isSubmitting: isSubmittingFollowUp,
                            onResetThread: {
                                followUpMessages = []
                                followUpQuery = ""
                                AICoachSessionStore.shared.save(key: trade.key, result: coachingResult, followUps: [])
                            },
                            onSubmit: submitFollowUpQuestion
                        )
                        
                        // 6. Compact Action Bar
                        TradeAICoachActionBar(
                            isSavedToNotes: isSavedToNotes,
                            isSavedToNotebook: isSavedToNotebook,
                            showCopiedAlert: showCopiedAlert,
                            onAppendNotes: appendToNotes,
                            onSaveNotebook: saveToNotebook,
                            onCopy: copyToClipboard,
                            onRegenerate: {
                                AICoachSessionStore.shared.clear(key: trade.key)
                                followUpMessages = []
                                Task { await runCoachingAnalysis() }
                            }
                        )
                    }
                }
                .padding(.horizontal, 16)
                .padding(.vertical, 12)
                .padding(.bottom, 24)
            }
            .background(AppColors.background)
            .navigationTitle("Risk AI Coach")
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .confirmationAction) {
                    Button("Done") {
                        dismiss()
                    }
                    .font(AppTypography.captionBold)
                    .foregroundColor(AppColors.primaryText)
                }
            }
            .sheet(isPresented: $showPhotoPicker) {
                UIKitImagePicker(isPresented: $showPhotoPicker) { data, _ in
                    if let img = UIImage(data: data) {
                        self.selectedChartImage = img
                        self.isAutoGeneratedChart = false
                        Task { await runCoachingAnalysis() }
                    }
                }
            }
            .sheet(isPresented: $showTraderProfileSheet) {
                TraderProfileSheet()
            }
            .sheet(isPresented: $showFullScreenChart) {
                if let img = selectedChartImage {
                    FullScreenChartLightboxView(image: img)
                }
            }
        }
        .task {
            if let cached = AICoachSessionStore.shared.get(key: trade.key) {
                self.coachingResult = cached.result
                self.followUpMessages = cached.followUps
                self.isLoading = false
                // Always fetch fresh market bars in background so activeBars and real-time live price are up to date
                Task {
                    await refreshActiveBars(force: self.isOpen)
                }
                return
            }
            if !hasAutoLoadedAttachment {
                hasAutoLoadedAttachment = true
                if selectedChartImage == nil {
                    let attachments = dataStore.attachmentsFor(ownerType: "trade", ownerId: trade.key)
                    if let firstImage = attachments.first(where: {
                        let fn = $0.name.lowercased()
                        return $0.mime.contains("image") || fn.hasSuffix(".jpg") || fn.hasSuffix(".png") || fn.hasSuffix(".jpeg")
                    }),
                    let data = TradeDataStore.shared.attachmentFileData(storagePath: firstImage.storagePath),
                    let img = UIImage(data: data) {
                        self.selectedChartImage = img
                        self.isAutoGeneratedChart = false
                    }
                }
            }
            await runCoachingAnalysis()
        }
    }
    
    // MARK: - Live Position Status Builder for AI Follow-ups
    private func buildLivePositionSnapshot(isVi: Bool) -> String {
        let currentTrade = dataStore.trades.first(where: { $0.key == trade.key }) ?? trade
        let latestBar = activeBars?.last
        let curPrice = latestBar?.close ?? currentTrade.avgExit ?? currentTrade.avgEntry
        let isShort = currentTrade.direction == .short
        
        let df = DateFormatter()
        df.dateFormat = "yyyy-MM-dd HH:mm"
        df.timeZone = TimeZone(identifier: dataStore.generalSettings.displayTimeZone) ?? .current
        let nowStr = df.string(from: Date())
        let openedStr = df.string(from: currentTrade.openedAt)
        
        let entryPriceStr = Formatters.price(currentTrade.avgEntry, symbol: currentTrade.symbol)
        let curPriceStr = Formatters.price(curPrice, symbol: currentTrade.symbol)
        let slStr = currentTrade.stopLoss.map { Formatters.price($0, symbol: currentTrade.symbol) } ?? (isVi ? "Chưa cài SL" : "Not Set")
        let tpStr = currentTrade.profitTarget.map { Formatters.price($0, symbol: currentTrade.symbol) } ?? (isVi ? "Chưa cài TP" : "Not Set")
        let volStr = String(format: "%.2f", NSDecimalNumber(decimal: currentTrade.quantity).doubleValue)
        
        // P&L and Points
        let priceDelta = isShort ? (currentTrade.avgEntry - curPrice) : (curPrice - currentTrade.avgEntry)
        let spec = AssetContractEngine.spec(for: currentTrade.symbol)
        let pipDivisor = spec.pipSize > 0 ? spec.pipSize : Decimal(string: "0.0001")!
        let pipsDelta = priceDelta / pipDivisor
        let pipsDeltaDouble = (pipsDelta as NSDecimalNumber).doubleValue
        let pipsDeltaStr = String(format: "%@%.1f pips", pipsDeltaDouble >= 0 ? "+" : "", pipsDeltaDouble)
        
        // Unrealized P&L
        let unpnl: Decimal = {
            if isOpen {
                return AssetContractEngine.calculateGrossPnl(
                    symbol: currentTrade.symbol,
                    direction: currentTrade.direction,
                    quantity: currentTrade.quantity,
                    entryPrice: currentTrade.avgEntry,
                    exitPrice: curPrice,
                    customMultiplier: AssetContractEngine.customMultiplier(for: currentTrade.symbol, multipliers: dataStore.multipliers),
                    conversionRates: dataStore.currencyConversion.rates
                )
            } else {
                return currentTrade.netPnl
            }
        }()
        let pnlDouble = (unpnl as NSDecimalNumber).doubleValue
        let pnlStr = (unpnl >= 0 ? "+$" : "-$") + String(format: "%.2f", abs(pnlDouble))
        
        // R-Multiple
        let rStr: String = {
            guard let sl = currentTrade.stopLoss else { return "N/A" }
            let riskPerUnit = abs(currentTrade.avgEntry - sl)
            guard riskPerUnit > 0 else { return "N/A" }
            let r = priceDelta / riskPerUnit
            let rDouble = (r as NSDecimalNumber).doubleValue
            return String(format: "%@%.2fR", rDouble >= 0 ? "+" : "", rDouble)
        }()
        
        // Target Distances
        let slDistStr: String = {
            guard let sl = currentTrade.stopLoss else { return isVi ? "Chưa cài" : "Not set" }
            let dist = abs(curPrice - sl)
            let pips = dist / pipDivisor
            return String(format: "%.1f pips (SL @ %@)", (pips as NSDecimalNumber).doubleValue, Formatters.price(sl, symbol: currentTrade.symbol))
        }()
        let tpDistStr: String = {
            guard let tp = currentTrade.profitTarget else { return isVi ? "Chưa cài" : "Not set" }
            let dist = abs(tp - curPrice)
            let pips = dist / pipDivisor
            return String(format: "%.1f pips (TP @ %@)", (pips as NSDecimalNumber).doubleValue, Formatters.price(tp, symbol: currentTrade.symbol))
        }()
        
        // Extremes reached (MFE / MAE)
        let extremesStr: String = {
            guard let b = activeBars, !b.isEmpty else { return "" }
            let highs = b.map { $0.high }
            let lows = b.map { $0.low }
            guard let maxH = highs.max(), let minL = lows.min() else { return "" }
            let bestPrice = isShort ? minL : maxH
            let worstPrice = isShort ? maxH : minL
            let bestDelta = isShort ? (currentTrade.avgEntry - bestPrice) : (bestPrice - currentTrade.avgEntry)
            let worstDelta = isShort ? (currentTrade.avgEntry - worstPrice) : (worstPrice - currentTrade.avgEntry)
            let bestPips = (bestDelta / pipDivisor as NSDecimalNumber).doubleValue
            let worstPips = (worstDelta / pipDivisor as NSDecimalNumber).doubleValue
            let bestPriceStr = Formatters.price(bestPrice, symbol: currentTrade.symbol)
            let worstPriceStr = Formatters.price(worstPrice, symbol: currentTrade.symbol)
            
            if isVi {
                return "\n  • Đỉnh lợi nhuận từng đạt (MFE): \(bestPriceStr) (\(String(format: "%@%.1f pips", bestPips >= 0 ? "+" : "", bestPips)))\n  • Mức sụt giảm tối đa từng chịu (MAE): \(worstPriceStr) (\(String(format: "%@%.1f pips", worstPips >= 0 ? "+" : "", worstPips)))"
            } else {
                return "\n  • Max Favorable Excursion (MFE Peak): \(bestPriceStr) (\(String(format: "%@%.1f pips", bestPips >= 0 ? "+" : "", bestPips)))\n  • Max Adverse Excursion (MAE Drawdown): \(worstPriceStr) (\(String(format: "%@%.1f pips", worstPips >= 0 ? "+" : "", worstPips)))"
            }
        }()
        
        // Recent 3-4 candles price action reaction
        let candleReactionStr: String = {
            guard let b = activeBars, b.count >= 2 else { return "" }
            let recent = Array(b.suffix(4))
            var lines: [String] = []
            for (idx, bar) in recent.enumerated() {
                let isLast = idx == recent.count - 1
                let label = isLast ? (isVi ? "Nến hiện tại" : "Current Bar") : "Bar -#\(recent.count - 1 - idx)"
                let o = Formatters.price(bar.open, symbol: currentTrade.symbol)
                let h = Formatters.price(bar.high, symbol: currentTrade.symbol)
                let l = Formatters.price(bar.low, symbol: currentTrade.symbol)
                let c = Formatters.price(bar.close, symbol: currentTrade.symbol)
                let direction = bar.close >= bar.open ? (isVi ? "TĂNG" : "BULL") : (isVi ? "GIẢM" : "BEAR")
                lines.append("  • \(label): O: \(o) | H: \(h) | L: \(l) | C: \(c) (\(direction))")
            }
            let header = isVi ? "\n- PHẢN ỨNG GIÁ & HÀNH VI NẾN GẦN NHẤT (PRICE ACTION REACTION):" : "\n- RECENT CANDLE PRICE ACTION REACTION:"
            return header + "\n" + lines.joined(separator: "\n")
        }()
        
        let durationStr: String = {
            let diff = Date().timeIntervalSince(currentTrade.openedAt)
            let mins = Int(max(1, diff / 60))
            let hours = mins / 60
            if hours > 0 {
                return "\(hours)h \(mins % 60)m"
            } else {
                return "\(mins)m"
            }
        }()
        
        if isVi {
            return """
            [TRẠNG THÁI LỆNH THỰC TẾ ĐẾN THỜI ĐIỂM HIỆN TẠI (THỜI GIAN: \(nowStr))]:
            - Trạng thái: \(isOpen ? "LỆNH ĐANG MỞ (LIVE RUNNING)" : "LỆNH ĐÃ ĐÓNG")
            - Cặp tiền: \(currentTrade.symbol) | Vị thế: \(isShort ? "SELL / SHORT" : "BUY / LONG") | Khối lượng: \(volStr) lots
            - Thời gian mở: \(openedStr) (Đã giữ lệnh: \(durationStr))
            - Giá vào (Entry): \(entryPriceStr)
            - GIÁ THỊ TRƯỜNG HIỆN TẠI: \(curPriceStr) (Biên độ giá: \(pipsDeltaStr))
            - LỢI NHUẬN TẠM TÍNH HIỆN TẠI: \(pnlStr) (Tỷ lệ: \(rStr))
            - Khoảng cách đến Cắt lỗ (SL): \(slDistStr)
            - Khoảng cách đến Chốt lời (TP): \(tpDistStr)\(extremesStr)\(candleReactionStr)
            """
        } else {
            return """
            [EXACT REAL-TIME POSITION STATE AT THIS MOMENT (TIMESTAMP: \(nowStr))]:
            - Position Status: \(isOpen ? "LIVE RUNNING POSITION" : "CLOSED POSITION")
            - Symbol: \(currentTrade.symbol) | Direction: \(isShort ? "SELL / SHORT" : "BUY / LONG") | Volume: \(volStr) lots
            - Opened At: \(openedStr) (Time elapsed: \(durationStr))
            - Entry Price: \(entryPriceStr)
            - CURRENT MARKET PRICE: \(curPriceStr) (Delta: \(pipsDeltaStr))
            - UNREALIZED P&L RIGHT NOW: \(pnlStr) (Current R: \(rStr))
            - Distance to Stop Loss (SL): \(slDistStr)
            - Distance to Take Profit (TP): \(tpDistStr)\(extremesStr)\(candleReactionStr)
            """
        }
    }

    // MARK: - Follow-Up Submission
    private func submitFollowUpQuestion() {
        let q = followUpQuery.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !q.isEmpty, !isSubmittingFollowUp else { return }
        
        let userMsg = AICoachMessage(role: "user", content: q)
        // Keep front-end messages clean (only user questions and AI replies)
        self.followUpMessages.append(userMsg)
        self.followUpQuery = ""
        self.isSubmittingFollowUp = true
        
        let chartBase64 = selectedChartImage?.jpegData(compressionQuality: 0.85)?.base64EncodedString()
        
        Task {
            // Always ensure the very latest real-time bars are fetched before sending question to AI
            if self.isOpen || self.activeBars == nil {
                await refreshActiveBars(force: true)
            }
            
            // Compose backend context: push initial coachingResult silently in history to AI
            var historyToSend: [AICoachMessage] = []
            if !self.coachingResult.isEmpty {
                historyToSend.append(AICoachMessage(role: "assistant", content: self.coachingResult))
            }
            historyToSend.append(contentsOf: self.followUpMessages)
            
            let isVi = (dataStore.aiSettings.language.isEmpty || dataStore.aiSettings.language == "vi")
            let liveSnapshot = buildLivePositionSnapshot(isVi: isVi)
            
            var promptComponents: [String] = []
            promptComponents.append(q)
            promptComponents.append(liveSnapshot)
            
            if let b = activeBars, !b.isEmpty {
                let window = MomentumEngine.computeWindow(bars: b, windowSize: 15)
                let momStr = MomentumEngine.formatMomentumTable(
                    window: window,
                    displayTimeZone: TimeZone(identifier: dataStore.generalSettings.displayTimeZone) ?? .current,
                    isVi: isVi
                )
                if !momStr.isEmpty {
                    promptComponents.append(momStr)
                }
            }
            
            var augmentedPrompt = promptComponents.joined(separator: "\n\n")
            if isVi {
                augmentedPrompt += "\n\n(BẮT BUỘC TRẢ LỜI 100% BẰNG TIẾNG VIỆT, đi thẳng vào câu hỏi của trader, căn cứ vào thực trạng vị thế, giá và động lượng ở trên để đánh giá chuẩn xác. Tuyệt đối không trả lời bằng tiếng Anh)."
            } else {
                augmentedPrompt += "\n\n(Please answer directly and concisely in English, assessing the real-time position state and price action above)."
            }
            
            do {
                let response = try await AIReflectionService.shared.requestReflection(
                    action: .ask,
                    prompt: augmentedPrompt,
                    metrics: nil,
                    edgeScore: nil,
                    language: dataStore.aiSettings.language,
                    chartImageBase64: chartBase64,
                    sessionSummary: nil,
                    conversationHistory: historyToSend
                )
                await MainActor.run {
                    self.followUpMessages.append(AICoachMessage(role: "assistant", content: response))
                    self.isSubmittingFollowUp = false
                    self.isSavedToNotes = false
                    self.isSavedToNotebook = false
                    AICoachSessionStore.shared.save(key: self.trade.key, result: self.coachingResult, followUps: self.followUpMessages)
                }
            } catch {
                await MainActor.run {
                    self.followUpMessages.append(AICoachMessage(role: "assistant", content: "Error: \(error.localizedDescription)"))
                    self.isSubmittingFollowUp = false
                }
            }
        }
    }
    
    // MARK: - Replay Chart Snapshot Renderer
    @MainActor
    private func renderChartSnapshot(bars: [MarketBar]) -> UIImage? {
        guard !bars.isEmpty else { return nil }
        let executions = dataStore.executions.filter { trade.executionIds.contains($0.id) }
        let chart = CandleChartView(
            visibleBars: bars,
            allBars: bars,
            totalBarsCount: bars.count,
            trade: trade,
            executions: executions,
            throughTimestamp: Int64(Date().timeIntervalSince1970 * 1000),
            unrealizedPnl: trade.netPnl
        )
        .frame(width: 420, height: 260)
        .background(AppColors.cardBackground)
        
        let renderer = ImageRenderer(content: chart)
        renderer.scale = 2.0
        return renderer.uiImage
    }
    
    // MARK: - Coaching Logic & Context Fetching
    private func refreshActiveBars(force: Bool = false) async {
        do {
            let res = try await MarketDataService.shared.fetchBarsForTrade(
                trade: trade,
                config: dataStore.marketConnections,
                resolution: selectedResolution,
                forceRefresh: force
            )
            await MainActor.run {
                self.activeBars = res.bars
                self.activeBarsCount = res.bars.count
                self.activeCandleProvider = res.provider
            }
        } catch {
            if let symRes = try? await MarketDataService.shared.fetchBarsForSymbol(
                symbol: trade.symbol,
                config: dataStore.marketConnections,
                resolution: selectedResolution,
                count: 100,
                forceRefresh: force
            ), !symRes.bars.isEmpty {
                await MainActor.run {
                    self.activeBars = symRes.bars
                    self.activeBarsCount = symRes.bars.count
                    self.activeCandleProvider = symRes.provider
                }
            }
        }
    }
    
    private func runCoachingAnalysis() async {
        await MainActor.run {
            self.isLoading = true
            self.errorMessage = nil
            self.isSavedToNotes = false
            self.isSavedToNotebook = false
        }
        
        var candleSummary: String? = nil
        var fetchedBars: [MarketBar]? = nil
        do {
            let res = try await MarketDataService.shared.fetchBarsForTrade(
                trade: trade,
                config: dataStore.marketConnections,
                resolution: selectedResolution,
                forceRefresh: isOpen
            )
            fetchedBars = res.bars
            
            await MainActor.run {
                self.activeCandleProvider = res.provider
                self.activeBarsCount = res.bars.count
            }
            
            if !res.bars.isEmpty {
                let recent = res.bars.suffix(12)
                let highs = recent.map { $0.high }
                let lows = recent.map { $0.low }
                let maxH = highs.max() ?? 0
                let minL = lows.min() ?? 0
                candleSummary = "Past \(recent.count) candles (\(selectedResolution) from \(res.provider)): High \(Formatters.price(maxH)), Low \(Formatters.price(minL)), Close \(Formatters.price(recent.last?.close ?? 0))."
            }
            
            if self.selectedChartImage == nil || self.isAutoGeneratedChart {
                let snapshot = await renderChartSnapshot(bars: res.bars)
                await MainActor.run {
                    if let s = snapshot {
                        self.selectedChartImage = s
                        self.isAutoGeneratedChart = true
                    }
                }
            }
        } catch {
            AppLogger.warning("Candle fetch for trade failed: \(error.localizedDescription). Proceeding with numerical metrics.")
        }
        
        // Secondary fallback to symbol-level candles to guarantee RSI Core indicators (100 bars)
        if fetchedBars == nil || (fetchedBars?.count ?? 0) < 30 {
            if let symRes = try? await MarketDataService.shared.fetchBarsForSymbol(
                symbol: trade.symbol,
                config: dataStore.marketConnections,
                resolution: selectedResolution,
                count: 100
            ), !symRes.bars.isEmpty {
                fetchedBars = symRes.bars
                await MainActor.run {
                    self.activeCandleProvider = symRes.provider
                    self.activeBarsCount = symRes.bars.count
                }
            }
        }
        
        await MainActor.run {
            self.activeBars = fetchedBars
        }
        
        let chartBase64 = selectedChartImage?.jpegData(compressionQuality: 0.85)?.base64EncodedString()
        
        do {
            let response = try await AIReflectionService.shared.requestTradeCoaching(
                trade: trade,
                language: dataStore.aiSettings.language,
                recentCandlesSummary: candleSummary,
                bars: fetchedBars,
                chartImageBase64: chartBase64,
                linkedPreTradePlan: linkedPreTradePlan
            )
            await MainActor.run {
                self.coachingResult = response
                self.isLoading = false
                AICoachSessionStore.shared.save(key: self.trade.key, result: response, followUps: self.followUpMessages)
                
                // If trade ended in loss or had logged mistakes, extract and persist a lesson for future setups
                if !self.isOpen && (self.trade.netPnl < 0 || !self.trade.mistakes.isEmpty) {
                    let lessonText = response.components(separatedBy: "### 4").last?
                        .trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
                    if !lessonText.isEmpty {
                        let cleanLesson = lessonText.prefix(250).description
                        let newLesson = TraderAILesson(
                            symbol: self.trade.symbol,
                            setupType: "\(self.trade.direction == .short ? "SELL" : "BUY") \(self.trade.symbol)",
                            mistakeTag: self.trade.mistakes.first,
                            lesson: cleanLesson,
                            context: "Lệnh \(self.trade.symbol) (\(Formatters.price(self.trade.netPnl))$)"
                        )
                        AIAdvisorMemoryEngine.shared.saveLesson(newLesson)
                    }
                }
            }
        } catch {
            await MainActor.run {
                self.errorMessage = error.localizedDescription
                self.isLoading = false
            }
        }
    }
    
    // MARK: - Document Content Builder
    private func fullCoachingContent() -> String {
        var fullText = coachingResult
        let followUps = followUpMessages.filter { $0.content != coachingResult }
        if !followUps.isEmpty {
            fullText += "\n\n### Follow-Up Discussion\n"
            for msg in followUps {
                if msg.role == "user" {
                    fullText += "\n• **Trader**: \(msg.content)\n"
                } else {
                    fullText += "\n• **Risk AI**: \(msg.content)\n"
                }
            }
        }
        return fullText
    }
    
    // MARK: - Note Actions
    private func appendToNotes() {
        guard !coachingResult.isEmpty else { return }
        let dateStr = JournalIds.todayDateString()
        let prefix = isOpen ? "Risk AI Audit (\(dateStr))" : "Risk AI Review (\(dateStr))"
        let currentTrade = dataStore.trades.first(where: { $0.key == trade.key }) ?? trade
        let existingNotes = currentTrade.notes ?? ""
        
        var additions: [String] = []
        let trimmedResult = coachingResult.trimmingCharacters(in: .whitespacesAndNewlines)
        let sampleExcerpt = String(trimmedResult.prefix(min(120, trimmedResult.count)))
        let initialAlreadyAppended = !existingNotes.isEmpty && !sampleExcerpt.isEmpty && existingNotes.contains(sampleExcerpt)
        
        if !initialAlreadyAppended {
            let sectionHeader = "### \(prefix)"
            additions.append("\(sectionHeader)\n\n\(coachingResult)")
        }
        
        let followUps = followUpMessages.filter { $0.content != coachingResult && !$0.content.hasPrefix("Error:") }
        var unappendedFollowUps: [AICoachMessage] = []
        for msg in followUps {
            let msgExcerpt = String(msg.content.trimmingCharacters(in: .whitespacesAndNewlines).prefix(min(60, msg.content.count)))
            if !msgExcerpt.isEmpty && !existingNotes.contains(msgExcerpt) {
                unappendedFollowUps.append(msg)
            }
        }
        
        if !unappendedFollowUps.isEmpty {
            var followUpText = ""
            if !existingNotes.contains("### Follow-Up Discussion") {
                followUpText += "### Follow-Up Discussion (\(dateStr))\n"
            }
            for msg in unappendedFollowUps {
                followUpText += "\n• **\(msg.role == "user" ? "Trader" : "Risk AI")**: \(msg.content)\n"
            }
            additions.append(followUpText)
        }
        
        guard !additions.isEmpty else {
            isSavedToNotes = true
            #if os(iOS)
            UINotificationFeedbackGenerator().notificationOccurred(.success)
            #endif
            return
        }
        
        let newContent = additions.joined(separator: "\n\n")
        let finalNotes = existingNotes.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
            ? newContent
            : "\(existingNotes)\n\n---\n\n\(newContent)"
        
        dataStore.updateTradeAnnotations(
            key: trade.key,
            notes: finalNotes,
            tags: currentTrade.tags,
            mistakes: currentTrade.mistakes,
            stopLoss: currentTrade.stopLoss,
            profitTarget: currentTrade.profitTarget,
            rating: currentTrade.rating,
            playbookId: currentTrade.playbookId,
            reviewedAt: Date()
        )
        
        if let updated = dataStore.trades.first(where: { $0.key == trade.key }) {
            onTradeUpdated?(updated)
        }
        
        isSavedToNotes = true
        #if os(iOS)
        UINotificationFeedbackGenerator().notificationOccurred(.success)
        #endif
    }
    
    private func saveToNotebook() {
        guard !coachingResult.isEmpty else { return }
        let targetFolderName = "Trade Insights"
        let folder: NotebookFolder
        if let existing = dataStore.folders.first(where: { $0.name.lowercased() == targetFolderName.lowercased() }) {
            folder = existing
        } else {
            do {
                folder = try dataStore.createFolder(name: targetFolderName)
            } catch {
                AppLogger.warning("Failed to create folder: \(error.localizedDescription)")
                return
            }
        }
        
        let dateStr = JournalIds.todayDateString()
        let title = isOpen
            ? "[Risk AI Live] \(trade.symbol) \(trade.side.uppercased()) (\(dateStr))"
            : "[Risk AI Audit] \(trade.symbol) \(trade.side.uppercased()) (\(dateStr))"
        let content = fullCoachingContent()
        let tags = ["#risk-ai", "#trade-audit", "#\(trade.symbol.lowercased())"]
        
        do {
            if let existingNoteId = createdNotebookNoteId {
                _ = try dataStore.patchNote(
                    id: existingNoteId,
                    title: title,
                    content: content,
                    tags: tags,
                    folderId: folder.id
                )
            } else {
                let note = try dataStore.createNote(
                    folderId: folder.id,
                    title: title,
                    content: content,
                    tags: tags,
                    tradeKey: trade.key,
                    dayDate: dateStr
                )
                createdNotebookNoteId = note.id
            }
            isSavedToNotebook = true
            #if os(iOS)
            UINotificationFeedbackGenerator().notificationOccurred(.success)
            #endif
        } catch {
            AppLogger.warning("Failed to save note: \(error.localizedDescription)")
        }
    }
    
    private func copyToClipboard() {
        UIPasteboard.general.string = fullCoachingContent()
        showCopiedAlert = true
        #if os(iOS)
        UIImpactFeedbackGenerator(style: .light).impactOccurred()
        #endif
        DispatchQueue.main.asyncAfter(deadline: .now() + 2) {
            showCopiedAlert = false
        }
    }
